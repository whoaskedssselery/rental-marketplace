param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$sourceRoot = Join-Path $repoRoot '.claude/skills'
$targetRoot = Join-Path $repoRoot '.agents/skills'
$sources = @(Get-ChildItem -LiteralPath $sourceRoot -Directory | Where-Object {
    Test-Path -LiteralPath (Join-Path $_.FullName 'SKILL.md')
} | Sort-Object Name)
if ($sources.Count -eq 0) { throw 'No Claude skills found.' }

$problems = [System.Collections.Generic.List[string]]::new()
foreach ($source in $sources) {
    $sourceFile = Join-Path $source.FullName 'SKILL.md'
    $body = [System.IO.File]::ReadAllText($sourceFile)
    $frontmatter = [regex]::Match($body, '\A---\r?\n(?<metadata>[\s\S]*?)\r?\n---(?:\r?\n|$)')
    if (-not $frontmatter.Success) { throw "Invalid frontmatter: $sourceFile" }
    foreach ($field in @('name', 'description')) {
        if (-not [regex]::IsMatch($frontmatter.Groups['metadata'].Value, "(?m)^${field}:\s*\S")) {
            throw "Missing ${field}: $sourceFile"
        }
    }
    $relativeSource = ".claude/skills/$($source.Name)/SKILL.md"
    $metadata = $frontmatter.Groups['metadata'].Value.Replace("`r`n", "`n")
    $expected = @"
---
$metadata
---

# Codex adapter

Read the complete canonical skill at ``$relativeSource`` before acting.
Resolve its relative references, scripts, templates and assets against
``.claude/skills/$($source.Name)/``, not this adapter directory.
Follow the Codex tool mappings and capability limitations in the repository's
``AGENTS.md``. Keep the working directory at the repository root for commands.
If a dependency is unavailable, state that limitation; do not claim it ran.

Generated by ``scripts/sync-codex-skills.ps1``. Edit the canonical source and
rerun the script instead of editing this adapter.
"@
    $expected = $expected.Replace("`r`n", "`n") + "`n"
    $targetDir = Join-Path $targetRoot $source.Name
    $targetFile = Join-Path $targetDir 'SKILL.md'
    if ($Check) {
        if (-not (Test-Path -LiteralPath $targetFile)) {
            $problems.Add("Missing adapter: $($source.Name)")
        } elseif ([System.IO.File]::ReadAllText($targetFile).Replace("`r`n", "`n") -cne $expected) {
            $problems.Add("Outdated adapter: $($source.Name)")
        }
    } else {
        if (Test-Path -LiteralPath $targetFile) {
            $existing = [System.IO.File]::ReadAllText($targetFile)
            if ($existing -notmatch 'Generated by `scripts/sync-codex-skills.ps1`') {
                throw "Refusing to overwrite an unmanaged skill: $targetFile"
            }
        }
        [System.IO.Directory]::CreateDirectory($targetDir) | Out-Null
        [System.IO.File]::WriteAllText($targetFile, $expected, [System.Text.UTF8Encoding]::new($false))
    }
}
if (Test-Path -LiteralPath $targetRoot) {
    foreach ($target in Get-ChildItem -LiteralPath $targetRoot -Directory) {
        if ($target.Name -notin $sources.Name) {
            $file = Join-Path $target.FullName 'SKILL.md'
            if ((Test-Path -LiteralPath $file) -and
                ([System.IO.File]::ReadAllText($file) -match 'Generated by `scripts/sync-codex-skills.ps1`')) {
                $problems.Add("Stale adapter (review and remove manually): $($target.Name)")
            }
        }
    }
}
if ($problems.Count -gt 0) { throw ($problems -join "`n") }
Write-Output "$($sources.Count) Claude skills: Codex adapters $(if ($Check) { 'verified' } else { 'synchronized' })."
